import cors from "cors";
import express from "express";
import helmet from "helmet";
import cookieParser from "cookie-parser";
import { authRouter } from "./modules/auth/auth.routes.js";
import { contractRouter } from "./modules/contracts/contract.routes.js";
import { workflowRouter } from "./modules/workflows/workflow.routes.js";
import { obligationRouter } from "./modules/obligations/obligation.routes.js";
import { vendorRouter } from "./modules/vendors/vendor.routes.js";
import { auditRouter } from "./modules/audit/audit.routes.js";
import { notificationRouter } from "./modules/notifications/notification.routes.js";
import { env } from "./config/env.js";
import { errorHandler } from "./common/error-handler.js";
import { healthRouter } from "./modules/health/health.routes.js";

export const app = express();
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({ origin: env.WEB_ORIGIN, credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.use(cookieParser());
app.use((req, res, next) => {
  const startedAt = Date.now();
  res.on("finish", () => console.info(JSON.stringify({ method: req.method, path: req.path, statusCode: res.statusCode, durationMs: Date.now() - startedAt })));
  next();
});
app.get("/", (_req, res) => res.json({ success: true, data: { name: "ContractSphere API", version: "0.1.0" } }));
app.use(`${env.API_PREFIX}/health`, healthRouter);
app.use(`${env.API_PREFIX}/auth`, authRouter);
app.use(`${env.API_PREFIX}/contracts`, contractRouter);
app.use(`${env.API_PREFIX}/workflows`, workflowRouter);
app.use(`${env.API_PREFIX}/obligations`, obligationRouter);
app.use(`${env.API_PREFIX}/vendors`, vendorRouter);
app.use(`${env.API_PREFIX}/audit-events`, auditRouter);
app.use(`${env.API_PREFIX}/notifications`, notificationRouter);
app.use((_req, res) => res.status(404).json({ success: false, error: { code: "NOT_FOUND", message: "Route not found." } }));
app.use(errorHandler);
